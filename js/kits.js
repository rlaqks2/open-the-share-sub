const KITS = KITS_RAW.map(([page, name, level, minutes, method]) => {
  const group = Object.keys(GROUPS).find(g => GROUPS[g].includes(method)) || "기타";
  return {
    id: "k" + String(page).padStart(2, "0"),
    page, name, level, minutes, method, group,
    give: GIVE_OVERRIDE[name] || GIVE_BY_GROUP[group] || "지역 복지기관",
    season: SEASON[name] || null,
    basePrice: (typeof PRICE !== "undefined" && PRICE[name]) || null,
    price: (typeof PRICE !== "undefined" && PRICE[name]) || null,
    img: `assets/kits/k${String(page).padStart(2, "0")}.jpg`,
  };
});

/* ---------- 관리자 수정 단가 불러오기 ----------
   ENDPOINT 설정 시: 구글 시트 '단가' 탭에서 불러옴 (모든 방문자에게 반영)
   미설정(미리보기) 시: 이 브라우저에 저장된 값만 반영 */
const PRICE_LOCAL_KEY = "ots_price_override";
function applyPriceMap(map) {
  if (!map || typeof map !== "object") return;
  KITS.forEach(k => {
    const v = Number(map[k.name]);
    if (Number.isFinite(v) && v > 0) k.price = Math.round(v);
  });
}
async function loadPriceOverrides() {
  const endpoint = typeof SITE_CONFIG !== "undefined" && SITE_CONFIG.ENDPOINT;
  if (endpoint) {
    try {
      const r = await fetch(endpoint + "?type=prices");
      if (r.ok) { applyPriceMap(await r.json()); return "remote"; }
    } catch (e) { console.warn("단가 불러오기 실패, 기본 단가 사용", e); }
    return "default";
  }
  try { applyPriceMap(JSON.parse(localStorage.getItem(PRICE_LOCAL_KEY))); } catch { }
  return "local";
}
